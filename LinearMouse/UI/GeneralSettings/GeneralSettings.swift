import Defaults
import LaunchAtLogin
import SwiftUI

struct GeneralSettings: View {
    @Default(.menuBarVisibilityMode) var menuBarVisibilityMode
    @Default(.menuBarBatteryDisplayMode) var menuBarBatteryDisplayMode
    @Default(.showInDock) var showInDock
    @Default(.bypassEventsFromOtherApplications) var bypassEventsFromOtherApplications
    @State private var permissionEnabled = false
    @State private var previewLaunchAtLogin = true

    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            SettingsCard(title: NSLocalizedString("Startup & appearance", comment: ""), symbol: "menubar.rectangle") {
                if ProcessEnvironment.isSettingsPreview {
                    SettingsToggleRow(title: NSLocalizedString("Launch at login", comment: ""), isOn: $previewLaunchAtLogin, fillsRow: true)
                } else {
                    LaunchAtLogin.Toggle {
                        Text("Launch at login")
                            .font(.body.weight(.medium))
                            .frame(maxWidth: .infinity, alignment: .leading)
                    }
                    .toggleStyle(.switch)
                    .controlSize(.small)
                    .frame(minHeight: 26)
                }
                Divider()
                languageControl
                Divider()
                menuBarControl
                Divider()
                SettingsToggleRow(title: NSLocalizedString("Show in Dock", comment: ""), isOn: $showInDock, fillsRow: true)
                Divider()
                batteryControls
                Divider()
                HStack(spacing: 10) {
                    if !showInDock && menuBarVisibilityMode != .always {
                        Text("Reopen MouseEasy from Applications to return to settings.")
                            .font(.callout)
                            .foregroundColor(.secondary)
                            .fixedSize(horizontal: false, vertical: true)
                    }
                    Spacer(minLength: 0)
                    Button(String(format: NSLocalizedString("Quit %@", comment: ""), LinearMouse.appName)) {
                        NSApplication.shared.terminate(nil)
                    }
                    .buttonStyle(SettingsSecondaryButtonStyle())
                }
            }

            SettingsCard(title: NSLocalizedString("Configuration & diagnostics", comment: ""), symbol: "archivebox") {
                ConfigurationSection()
                ConfigurationSection(showsMaintenance: true)
                Divider()
                SettingsDisclosure(title: NSLocalizedString("Diagnostic logs", comment: "")) {
                    LoggingSection()
                }
            }

            if !permissionEnabled, !ProcessEnvironment.isSettingsPreview {
                SettingsCard(title: NSLocalizedString("Device control permission", comment: ""), symbol: "lock.shield") {
                    permissionControl
                }
            }

            SettingsDisclosure(title: NSLocalizedString("Compatibility & version", comment: "")) {
                if !ProcessEnvironment.isSettingsPreview, permissionEnabled {
                    permissionControl
                }
                SettingsToggleRow(
                    title: NSLocalizedString("Skip input generated by other apps", comment: ""),
                    subtitle: NSLocalizedString("Let tools such as Logi Options+ handle their own events.", comment: ""),
                    isOn: $bypassEventsFromOtherApplications
                )
                HStack(spacing: 10) {
                    Text("MouseEasy \(LinearMouse.appVersion)")
                        .foregroundColor(.secondary)
                    if let project = ProjectLinks.shared.repository {
                        Link("Project repository", destination: project)
                    }
                    if let license = ProjectLinks.license {
                        Button("Licenses") { NSWorkspace.shared.open(license) }
                            .buttonStyle(SettingsSecondaryButtonStyle())
                    }
                    Link("Upstream: LinearMouse", destination: ProjectLinks.upstream)
                }
            }
            .padding(.horizontal, 4)
        }
        .onAppear(perform: refreshPermission)
        .onReceive(NotificationCenter.default.publisher(for: NSApplication.didBecomeActiveNotification)) { _ in
            refreshPermission()
        }
    }

    private var languageControl: some View {
        HStack {
            Text("Language")
            Spacer(minLength: 12)
            Picker("Language", selection: Binding(
                get: { InterfaceLanguage.current },
                set: { $0.apply() }
            )) {
                Text("System default").tag(InterfaceLanguage.system)
                Text(verbatim: "简体中文").tag(InterfaceLanguage.chinese)
                Text(verbatim: "English").tag(InterfaceLanguage.english)
            }
            .labelsHidden()
            .frame(width: 165)
        }
        .help("Changing the language restarts MouseEasy.")
    }

    private var menuBarControl: some View {
        HStack(spacing: 10) {
            Text("Menu bar icon")
            Spacer(minLength: 12)
            Picker("Menu bar icon", selection: $menuBarVisibilityMode) {
                Text("Always show").tag(MenuBarVisibilityMode.always)
                Text("When attention is needed").tag(MenuBarVisibilityMode.whenAttentionNeeded)
                Text("Hide").tag(MenuBarVisibilityMode.never)
            }
            .labelsHidden()
            .pickerStyle(.menu)
            .frame(width: 165)
        }
        .frame(minHeight: 26)
    }

    private var permissionControl: some View {
        HStack(spacing: 10) {
            Text("Device control permission")
            Text(permissionEnabled ? NSLocalizedString("Granted", comment: "") : NSLocalizedString("Permission needed", comment: ""))
                .foregroundColor(permissionEnabled ? .secondary : .orange)
            Button("Open System Settings") {
                AccessibilityPermission.openSettings()
            }
            .buttonStyle(SettingsSecondaryButtonStyle())
        }
        .help(permissionPaneName)
    }

    private func refreshPermission() {
        guard !ProcessEnvironment.isSettingsPreview else { return }
        AccessibilityPermission.check { snapshot in
            permissionEnabled = snapshot.enabled
        }
    }

    private var permissionPaneName: String {
        NSLocalizedString(AccessibilityPermission.Naming.current.settingsPaneKey, comment: "System privacy pane")
    }

    private var batteryControls: some View {
        HStack(spacing: 10) {
            Text("Menu bar battery level")
            Spacer(minLength: 12)
            Picker("Show battery level in menu bar", selection: $menuBarBatteryDisplayMode.animation()) {
                Text("Off").tag(MenuBarBatteryDisplayMode.off)
                batteryThresholdText(5).tag(MenuBarBatteryDisplayMode.below5)
                batteryThresholdText(10).tag(MenuBarBatteryDisplayMode.below10)
                batteryThresholdText(15).tag(MenuBarBatteryDisplayMode.below15)
                batteryThresholdText(20).tag(MenuBarBatteryDisplayMode.below20)
                Text("Always show").tag(MenuBarBatteryDisplayMode.always)
            }
            .labelsHidden()
            .pickerStyle(.menu)
            .frame(width: 165)
            .disabled(menuBarVisibilityMode == .never)
        }
        .help("Requires a device that reports its battery level.")
    }

    private func batteryThresholdText(_ threshold: Int) -> Text {
        Text(String(format: NSLocalizedString("%@ or below", comment: ""), formattedPercent(threshold)))
    }
}
