import CoreGraphics
import Foundation
import os.log

/// iPhone Mirroring observes the global HID delivery path. Rebuild the final
/// wheel sample instead of only mutating the original sample's CGEvent fields.
/// The real-phone result still needs to be checked on each supported macOS.
enum IPhoneMirroringScrollCompatibility {
    static let bundleIdentifier = "com.apple.ScreenContinuity"
    static let repostedEventMarker: Int64 = 0x4D57_4950_484F_4E45
    private static let log = OSLog(subsystem: Bundle.main.bundleIdentifier ?? "MouseEasy", category: "MirroringWheel")

    static func shouldUse(bundleIdentifier: String?, isMouse: Bool) -> Bool {
        isMouse && bundleIdentifier == Self.bundleIdentifier
    }

    static func isReposted(_ event: CGEvent) -> Bool {
        event.getIntegerValueField(.eventSourceUserData) == repostedEventMarker
    }

    /// This query is necessary even when the user has no per-app configuration.
    static func requiresProcessResolution(for event: CGEvent) -> Bool {
        event.type == .scrollWheel && !isReposted(event)
    }

    static func recordInput(_ event: CGEvent, mode: String) {
        os_log("Mirror wheel input mode=%{public}@ x=%{public}.3f y=%{public}.3f flags=%{public}llu",
               log: log, type: .info, mode,
               event.getDoubleValueField(.scrollWheelEventFixedPtDeltaAxis2),
               event.getDoubleValueField(.scrollWheelEventFixedPtDeltaAxis1), event.flags.rawValue)
    }

    static func makeRepostedEvent(from event: CGEvent, usesCanonicalPixelDeltas: Bool = false) -> CGEvent? {
        guard !isReposted(event) else {
            return nil
        }

        // Gesture companion events generated by the smooth engine must use
        // the same delivery path as their corresponding wheel samples.
        guard event.type == .scrollWheel else {
            guard let copy = event.copy() else { return nil }
            copy.setIntegerValueField(.eventSourceUserData, value: repostedEventMarker)
            return copy
        }

        let continuous = event.getIntegerValueField(.scrollWheelEventIsContinuous) != 0
        let constructorFields: [CGEventField] = continuous
            ? [.scrollWheelEventPointDeltaAxis1, .scrollWheelEventPointDeltaAxis2, .scrollWheelEventPointDeltaAxis3]
            : [.scrollWheelEventDeltaAxis1, .scrollWheelEventDeltaAxis2, .scrollWheelEventDeltaAxis3]
        let constructorDeltas = constructorFields.map { event.getDoubleValueField($0) }
        guard constructorDeltas.allSatisfy(\.isFinite),
              let rebuilt = CGEvent(
                  scrollWheelEvent2Source: nil,
                  units: continuous ? .pixel : .line,
                  wheelCount: 3,
                  wheel1: constructorInteger(constructorDeltas[0]),
                  wheel2: constructorInteger(constructorDeltas[1]),
                  wheel3: constructorInteger(constructorDeltas[2])
              ) else {
            return nil
        }

        // Keep zero-delta ending events so an iPhone scroll does not remain active.
        let metadataFields: [CGEventField] = [
            .scrollWheelEventIsContinuous, .scrollWheelEventScrollPhase,
            .scrollWheelEventMomentumPhase, .scrollWheelEventScrollCount
        ]
        for field in metadataFields {
            rebuilt.setIntegerValueField(field, value: event.getIntegerValueField(field))
        }
        if !usesCanonicalPixelDeltas || !continuous {
            let lineFields: [CGEventField] = [
                .scrollWheelEventDeltaAxis1, .scrollWheelEventDeltaAxis2, .scrollWheelEventDeltaAxis3
            ]
            for field in lineFields {
                rebuilt.setIntegerValueField(field, value: event.getIntegerValueField(field))
            }
            let preciseFields: [CGEventField] = [
                .scrollWheelEventFixedPtDeltaAxis1, .scrollWheelEventFixedPtDeltaAxis2,
                .scrollWheelEventFixedPtDeltaAxis3, .scrollWheelEventPointDeltaAxis1,
                .scrollWheelEventPointDeltaAxis2, .scrollWheelEventPointDeltaAxis3
            ]
            for field in preciseFields {
                let value = event.getDoubleValueField(field)
                guard value.isFinite else { return nil }
                rebuilt.setDoubleValueField(field, value: value)
            }
        }
        // A synthetic pixel frame already supplied its point deltas to the
        // system constructor. Keep the system's matching fixed and line deltas.
        rebuilt.location = event.location
        rebuilt.flags = event.flags
        rebuilt.setIntegerValueField(.eventSourceUserData, value: repostedEventMarker)
        return rebuilt
    }

    @discardableResult
    static func post(
        _ event: CGEvent,
        preservesSourceEvent: Bool = false,
        usesCanonicalPixelDeltas: Bool = false,
        using sink: (CGEvent, CGEventTapLocation) -> Void
    ) -> Bool {
        guard !isReposted(event),
              let repost = preservesSourceEvent ? event.copy() : makeRepostedEvent(
                  from: event, usesCanonicalPixelDeltas: usesCanonicalPixelDeltas
              ) else { return false }
        // A reversal-only wheel keeps the source's timestamp and event data.
        repost.setIntegerValueField(.eventSourceUserData, value: repostedEventMarker)
        sink(repost, .cghidEventTap)
        return true
    }

    private static func constructorInteger(_ value: Double) -> Int32 {
        Int32(min(Double(Int32.max), max(Double(Int32.min), value.rounded())))
    }
}
